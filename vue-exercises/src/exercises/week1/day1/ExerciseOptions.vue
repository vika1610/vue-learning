  Теория: theory.md, часть 6 «Как было раньше: Options API».

  Условие:
  1. Заведи данные (имя и возраст) в опции data().
  2. Выведи их в шаблоне через {{ }}: «Меня зовут …, мне … лет».
  3. Добавь в methods функцию, которая возвращает возраст через 5 лет,
     и вызови её в шаблоне. Внутри метода данные доступны через this.
  4. Сравни с Exercise.vue: что пришлось писать дополнительно?

